const {stripTypeScriptTypes}=require('node:module');
const source=fs.readFileSync(path.join(__dirname,'supabase/functions/assistente-stefano/index.ts'),'utf8');
const js=stripTypeScriptTypes(source,{mode:'strip'}).replace(/^import .*;$/m,'');
const context={createClient:()=>({}),Deno:{env:{get:()=>''},serve:()=>{}},URL,AbortSignal,Uint8Array,Response,console};vm.createContext(context);vm.runInContext(js,context);
for(const request of ['Audit di sicurezza del codice Python','Analizza una SQL injection nel mio laboratorio','Pentest autorizzato di una API','Cybersecurity e hardening Linux'])assert.equal(context.autoModeForObjective(request),'security',request);
assert.equal(context.autoModeForObjective('Fammi un volantino per un corso cybersecurity'),'graphics');
